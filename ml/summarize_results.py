#!/usr/bin/env python3
"""summarize_results: collect every eval_*/episodes.jsonl under runs/ into one table.

For each (method, perturbation): mean over the 3 training seeds of success / collision /
progress, the seed-to-seed spread, and a 95% bootstrap CI over the pooled episodes. The
baseline (pre-9/23 student, evaluated on 40 tasks per map) is cut to the same first 30
tasks per map so every row is on the identical task set. Writes docs/results/.

    python3 ml/summarize_results.py
"""
import glob, json, os, re, collections
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNS = os.path.join(ROOT, 'runs'); OUT = os.path.join(ROOT, 'docs', 'results')
N_TASKS = 30
METHODS = [('baseline', 'Pre-9/23 student (BC, video data)'), ('bc_noaug', 'BC, clean data'),
           ('bc_aug', 'BC + augmentation'), ('dagger_r1', 'DAgger round 1'),
           ('dagger_r2', 'DAgger round 2'), ('dagger_r3', 'DAgger round 3'),
           ('dcl_r1', 'DAgger from BC, round 1'), ('dcl_r2', 'DAgger from BC, round 2'),
           ('dcl_r3', 'DAgger from BC, round 3'),
           ('abl_lidar', 'BC, lidar input only'), ('abl_camera', 'BC, camera input only')]


def load(path):
    rows = [json.loads(l) for l in open(path)]
    return [r for r in rows if int(r['task_id'].rsplit(':', 1)[1]) < N_TASKS]


def boot_ci(x, n=2000, seed=0):
    x = np.asarray(x, float); rng = np.random.default_rng(seed)
    m = rng.choice(x, (n, len(x))).mean(1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main():
    os.makedirs(OUT, exist_ok=True)
    table = collections.OrderedDict()
    for key, label in METHODS:
        for pert in ('none', 'lidar', 'camera', 'nocam'):
            if key == 'baseline':
                paths = glob.glob(os.path.join(RUNS, 'baseline', f'eval_{pert}', 'episodes.jsonl'))
                paths += glob.glob(os.path.join(RUNS, 'eval', 'baseline' if pert == 'none' else '__none__', 'episodes.jsonl'))[:0]
            else:
                base, _, rnd = key.partition('_r')
                pat = f'{base}_s*_r{rnd}' if rnd else f'{key}_s*'
                paths = sorted(glob.glob(os.path.join(RUNS, pat, f'eval_{pert}', 'episodes.jsonl')))
            if not paths: continue
            per_seed = [load(p) for p in paths]
            pooled = [r for s in per_seed for r in s]
            def stat(k):
                seeds = [np.mean([float(r[k]) for r in s]) for s in per_seed]
                v = [float(r[k]) for r in pooled]
                lo, hi = boot_ci(v)
                return {'mean': float(np.mean(v)), 'seed_sd': float(np.std(seeds)), 'ci': [lo, hi],
                        'per_seed': [round(x, 4) for x in seeds]}
            unseen = [r for r in pooled if r['map'] == 'uploadtest']
            table[f'{key}/{pert}'] = {
                'label': label, 'perturb': pert, 'seeds': len(per_seed), 'episodes': len(pooled),
                'success': stat('success'), 'collided': stat('collided'), 'progress': stat('progress'),
                'unseen_map_success': float(np.mean([r['success'] for r in unseen])) if unseen else None,
                'unseen_map_progress': float(np.mean([r['progress'] for r in unseen])) if unseen else None}
    json.dump(table, open(os.path.join(OUT, 'closed_loop_2026-09-23.json'), 'w'), indent=1)
    # plain-text summary
    lines = ['method | perturb | seeds | eps | success % (95% CI) | collision % | progress % | unseen-map success %']
    for k, v in table.items():
        s, c, p = v['success'], v['collided'], v['progress']
        u = '' if v['unseen_map_success'] is None else f"{100 * v['unseen_map_success']:.1f}"
        lines.append(f"{v['label']} | {v['perturb']} | {v['seeds']} | {v['episodes']} | {100 * s['mean']:.1f} "
                     f"({100 * s['ci'][0]:.1f}-{100 * s['ci'][1]:.1f}) | {100 * c['mean']:.1f} | {100 * p['mean']:.1f} | {u}")
    open(os.path.join(OUT, 'closed_loop_2026-09-23.txt'), 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    # LaTeX: one macro per number the report quotes, and the main table
    def mac(name, val): return f'\\newcommand{{\\{name}}}{{{val}}}\n'
    tex = '% generated by ml/summarize_results.py -- do not edit\n'
    # every macro the report can use exists, even for runs that have not finished ("n/a")
    for m in ('Base', 'Bc', 'Bcaug', 'Dgone', 'Dgtwo', 'Dgthree', 'Dcone', 'Dctwo', 'Dcthree', 'Abllid', 'Ablcam'):
        for pt in ('Nom', 'Lid', 'Cam', 'Nocam'):
            for suf in ('Succ', 'SuccLo', 'SuccHi', 'SuccSd', 'Coll', 'Prog', 'Unseen', 'UnseenProg'):
                tex += f'\\providecommand{{\\res{m}{pt}{suf}}}{{n/a}}\n'
    defaults = tex; tex = ''          # written after the real values; \providecommand skips those
    alpha = {'baseline': 'Base', 'bc_noaug': 'Bc', 'bc_aug': 'Bcaug', 'dagger_r1': 'Dgone',
             'dagger_r2': 'Dgtwo', 'dagger_r3': 'Dgthree', 'dcl_r1': 'Dcone', 'dcl_r2': 'Dctwo', 'dcl_r3': 'Dcthree', 'abl_lidar': 'Abllid', 'abl_camera': 'Ablcam'}
    palpha = {'none': 'Nom', 'lidar': 'Lid', 'camera': 'Cam', 'nocam': 'Nocam'}
    for k, v in table.items():
        m, pt = k.split('/'); pre = 'res' + alpha[m] + palpha[pt]
        tex += mac(pre + 'Succ', f"{100 * v['success']['mean']:.1f}")
        tex += mac(pre + 'SuccLo', f"{100 * v['success']['ci'][0]:.1f}")
        tex += mac(pre + 'SuccHi', f"{100 * v['success']['ci'][1]:.1f}")
        tex += mac(pre + 'SuccSd', f"{100 * v['success']['seed_sd']:.1f}")
        tex += mac(pre + 'Coll', f"{100 * v['collided']['mean']:.1f}")
        tex += mac(pre + 'Prog', f"{100 * v['progress']['mean']:.1f}")
        if v['unseen_map_success'] is not None:
            tex += mac(pre + 'Unseen', f"{100 * v['unseen_map_success']:.1f}")
            tex += mac(pre + 'UnseenProg', f"{100 * v['unseen_map_progress']:.1f}")
    open(os.path.join(OUT, 'numbers.tex'), 'w').write(tex + defaults)
    rows = []
    for k, v in table.items():
        if v['perturb'] != 'none' or k.startswith('abl_'): continue
        s, c, p = v['success'], v['collided'], v['progress']
        u = '--' if v['unseen_map_success'] is None else f"{100 * v['unseen_map_success']:.1f}"
        rows.append(f"    {v['label']} & {v['seeds']} & {100 * s['mean']:.1f} [{100 * s['ci'][0]:.1f}, {100 * s['ci'][1]:.1f}] "
                    f"& {100 * c['mean']:.1f} & {100 * p['mean']:.1f} & {u} \\\\")
    open(os.path.join(OUT, 'table_nominal.tex'), 'w').write('\n'.join(rows) + '\n')
    rows = []
    for m in ('baseline', 'bc_noaug', 'bc_aug', 'dagger_r3', 'dcl_r3'):
        if not any(k.startswith(m + '/') for k in table): continue
        cells = []
        for pt in ('none', 'lidar', 'camera', 'nocam'):
            v = table.get(f'{m}/{pt}')
            cells.append('--' if v is None else f"{100 * v['success']['mean']:.1f} / {100 * v['progress']['mean']:.0f}")
        lab = dict(METHODS)[m]
        rows.append(f"    {lab} & " + ' & '.join(cells) + ' \\\\')
    open(os.path.join(OUT, 'table_robust.tex'), 'w').write('\n'.join(rows) + '\n')
    # figure: nominal success / collision / progress by method
    try:
        import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
        rows = [(v['label'], v) for k, v in table.items() if v['perturb'] == 'none' and not k.startswith('abl_')]
        fig, ax = plt.subplots(1, 3, figsize=(11, 3.4), sharey=False)
        for i, (m, t) in enumerate((('success', 'Goal reached, no collision'), ('collided', 'Collision'),
                                    ('progress', 'Route progress'))):
            y = [100 * v[m]['mean'] for _, v in rows]
            err = np.array([[100 * (v[m]['mean'] - v[m]['ci'][0]), 100 * (v[m]['ci'][1] - v[m]['mean'])] for _, v in rows]).T
            ax[i].bar(range(len(rows)), y, yerr=err, color='#4C72B0' if m != 'collided' else '#C44E52', capsize=3)
            ax[i].set_xticks(range(len(rows))); ax[i].set_xticklabels([l for l, _ in rows], rotation=35, ha='right', fontsize=7)
            ax[i].set_title(t + ' (%)', fontsize=9); ax[i].set_ylim(0, 100); ax[i].grid(axis='y', alpha=.3)
        fig.tight_layout(); fig.savefig(os.path.join(OUT, 'closed_loop_2026-09-23.pdf')); fig.savefig(os.path.join(OUT, 'closed_loop_2026-09-23.png'), dpi=160)
    except Exception as e:
        print('figure skipped:', e)


if __name__ == '__main__':
    main()
